def add(
    subs: OrderedDict[str, list],
    sub: str,
    name: str,
    fr: int | None,
    to: int | None = None,
) -> None:
    price: dict = {}
    if fr is not None:
        price["from"] = fr
    if to is not None:
        price["to"] = to
    entry: dict = {"name": name}
    if price:
        entry["price"] = price
    subs.setdefault(sub, []).append(entry)


